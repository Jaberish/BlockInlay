/**
 * The drawn boards — the opening chapters of the game.
 *
 * These are the ones meant to look like something: a heart, a cat, a key, an
 * anchor. The generated boards that follow (see generated.ts) make fine puzzles
 * but are deliberate abstract shapes rather than pictures of things, and they go
 * unnamed — a number is a more honest label for them than an invented word.
 * Hand-drawing is spent here because this is where players look hardest.
 *
 * 200 is close to the ceiling. In a 10x10 grid at 18-46 cells there are only so
 * many shapes that genuinely read as an object; past this, drawing produces
 * "blob that was meant to be a lamp", which is worse than a clean abstract shape
 * because it visibly fails at something the abstract one never promised.
 *
 * The silhouettes are drawn by hand; the piece cuts are not. Each was found by
 * searching thousands of ways to carve the board and keeping a cut with exactly
 * one tiling — the same bar every generated level clears, re-checked for all of
 * them by `npm run verify-levels`.
 *
 * `nodes` is the difficulty score: how many piece placements a solver has to try
 * before the board is proven to have exactly one solution. Levels are ordered by
 * it, and the Warm-up/Easy/.../Expert labels are cut from it.
 */
